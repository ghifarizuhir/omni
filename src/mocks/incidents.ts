export const getIncidentById = (id: string): Incident | undefined =>
  mockIncidents.find(i => i.id === id || i.publicId === id);

export const getIncidentsByCI = (ciId: string): Incident[] =>
  mockIncidents.filter(
    i => i.affectedCIIds.includes(ciId) || i.affectedCIPublicIds.includes(ciId),
  );

export const getIncidentsByProblem = (problemPublicId: string): Incident[] =>
  mockIncidents.filter(i => i.linkedProblemPublicId === problemPublicId);

export const getActiveIncidents = (): Incident[] =>
  mockIncidents.filter(i => !['resolved', 'closed'].includes(i.status));

export const getMajorIncidents = (): Incident[] =>
  mockIncidents.filter(i => i.isMajor);
