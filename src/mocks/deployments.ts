export const getDeploymentById = (id: string) =>
  mockDeployments.find(d => d.id === id || d.publicId === id);

export const getActiveDeployments = () =>
  mockDeployments.filter(d => ['pending', 'running', 'rolling_back'].includes(d.status));

export const getDeploymentsByEnv = (env: Environment) =>
  mockDeployments.filter(d => d.environment === env);

export const getDeploymentsByRelease = (releaseId: string) =>
  mockDeployments.filter(d => d.linkedReleaseId === releaseId || d.linkedReleasePublicId === releaseId);

export const getRecentDeployments = (env: Environment, hours: number) => {
  const cutoff = new Date(Date.now() - hours * 3600 * 1000).toISOString();
  return mockDeployments.filter(
    d => d.environment === env && (d.startedAt ?? '') >= cutoff
  );
};
